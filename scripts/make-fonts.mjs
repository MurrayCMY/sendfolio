// Bundles the fonts used inside generated PDFs as base64 TypeScript modules, so the Netlify function
// does not depend on files being present on disk at runtime.
//   - Noto Sans SC "chinese-simplified" slice (CJK + ASCII)
//   - Jost latin-ext (for characters such as the "e with macron" in the brand name)
// The sources are WOFF (zlib-compressed tables). fontkit re-decompresses a table on every glyph access, which made
// PDF generation take minutes, so they are unpacked to plain TrueType (sfnt) here, once.
import fs from "node:fs";
import zlib from "node:zlib";

function woffToSfnt(buf) {
  if (buf.toString("latin1", 0, 4) !== "wOFF") throw new Error("not a WOFF file");
  const flavor = buf.readUInt32BE(4);
  const numTables = buf.readUInt16BE(12);
  const tables = [];
  for (let i = 0; i < numTables; i++) {
    const o = 44 + i * 20;
    const tag = buf.toString("latin1", o, o + 4);
    const offset = buf.readUInt32BE(o + 4);
    const compLength = buf.readUInt32BE(o + 8);
    const origLength = buf.readUInt32BE(o + 12);
    const checksum = buf.readUInt32BE(o + 16);
    const raw = buf.subarray(offset, offset + compLength);
    const data = compLength < origLength ? zlib.inflateSync(raw) : raw;
    if (data.length !== origLength) throw new Error(`bad table length for ${tag}`);
    tables.push({ tag, checksum, data });
  }
  let pow = 1, entrySelector = 0;
  while (pow * 2 <= numTables) { pow *= 2; entrySelector++; }
  const searchRange = pow * 16;
  const headerSize = 12 + numTables * 16;
  let offset = headerSize;
  const parts = [];
  const header = Buffer.alloc(headerSize);
  header.writeUInt32BE(flavor, 0);
  header.writeUInt16BE(numTables, 4);
  header.writeUInt16BE(searchRange, 6);
  header.writeUInt16BE(entrySelector, 8);
  header.writeUInt16BE(numTables * 16 - searchRange, 10);
  tables.forEach((t, i) => {
    const r = 12 + i * 16;
    header.write(t.tag, r, "latin1");
    header.writeUInt32BE(t.checksum, r + 4);
    header.writeUInt32BE(offset, r + 8);
    header.writeUInt32BE(t.data.length, r + 12);
    const pad = (4 - (t.data.length % 4)) % 4;
    parts.push(t.data, Buffer.alloc(pad));
    offset += t.data.length + pad;
  });
  return Buffer.concat([header, ...parts]);
}

const out = "netlify/functions/lib/font-data.ts";
const noto = woffToSfnt(fs.readFileSync("node_modules/@fontsource/noto-sans-sc/files/noto-sans-sc-chinese-simplified-400-normal.woff"));
const jost = woffToSfnt(fs.readFileSync("node_modules/@fontsource/jost/files/jost-latin-ext-400-normal.woff"));
fs.writeFileSync(
  out,
  `// Generated by scripts/make-fonts.mjs - do not edit. Fonts are SIL Open Font License (TrueType, unpacked from WOFF).\n` +
    `export const NOTO_SANS_SC_B64 = "${noto.toString("base64")}";\n` +
    `export const JOST_LATIN_EXT_B64 = "${jost.toString("base64")}";\n`,
);
console.log("wrote", out, Math.round(fs.statSync(out).size / 1024), "KB", "| noto TTF", Math.round(noto.length / 1024), "KB");
